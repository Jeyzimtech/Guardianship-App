import fs from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { Workbook, SpreadsheetFile } from '@oai/artifact-tool';
const dir = new URL('../', import.meta.url);
const csv = await fs.readFile(new URL('EduConnect-testers.csv', dir), 'utf8');
const wb = await Workbook.fromCSV(csv, { sheetName: 'Testers' });
const sheet = wb.worksheets.getItem('Testers');
sheet.getRange('A1:A18').format.font = { name: 'Arial', size: 11 };
sheet.getRange('A1:A18').format.columnWidth = 48;
sheet.getRange('A1:A18').format.rowHeight = 22;
sheet.showGridLines = false;
wb.recalculate();
const values = sheet.getRange('A1:A18').values.flat();
if (values.length !== 18 || new Set(values).size !== 18) throw new Error('Tester count mismatch');
const xlsx = await SpreadsheetFile.exportXlsx(wb);
await xlsx.save(fileURLToPath(new URL('EduConnect-testers.xlsx', dir)));
const preview = await wb.render({ sheetName: 'Testers', range: 'A1:A18', scale: 1, format: 'png' });
await fs.writeFile(new URL('preview.png', import.meta.url), new Uint8Array(await preview.arrayBuffer()));
console.log('Saved Excel workbook with 18 unique tester emails.');
